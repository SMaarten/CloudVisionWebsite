const languageSelect = document.getElementById("language-select");
const originalText = new Map();
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
let textNode;

while ((textNode = textWalker.nextNode())) {
  if (textNode.parentElement.closest("script, style")) continue;
  originalText.set(textNode, textNode.nodeValue);
}

const originalTitle = document.title;
const description = document.querySelector('meta[name="description"]');
const originalDescription = description.content;
const originalAriaLabels = new Map(
  [...document.querySelectorAll("[aria-label]")].map((element) => [element, element.getAttribute("aria-label")])
);

function setLanguage(language) {
  const dictionary = translations[language];
  originalText.forEach((original, node) => {
    const value = original.trim();
    const translated = dictionary[value];
    node.nodeValue = translated ? original.replace(value, translated) : original;
  });

  document.documentElement.lang = language;
  document.title = titleTranslations[language]?.[originalTitle] || originalTitle;
  description.content = language === "nl" ? originalDescription : descriptionTranslations[language];
  languageSelect.value = language;

  originalAriaLabels.forEach((original, element) => {
    element.setAttribute("aria-label", attributeTranslations[language]?.[original] || original);
  });
}

languageSelect.addEventListener("change", () => setLanguage(languageSelect.value));

document.getElementById("copy").addEventListener("click", async (event) => {
  const button = event.currentTarget;
  const email = document.getElementById("mail");
  const messages = {
    nl: { copy: "Kopieer", copied: "Gekopieerd", selected: "Geselecteerd" },
    fr: { copy: "Copier", copied: "Copié", selected: "Sélectionné" },
    en: { copy: "Copy", copied: "Copied", selected: "Selected" }
  }[languageSelect.value];

  try {
    await navigator.clipboard.writeText(email.textContent);
    button.textContent = messages.copied;
  } catch {
    const range = document.createRange();
    range.selectNodeContents(email);
    const selection = window.getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
    button.textContent = messages.selected;
  }

  window.setTimeout(() => { button.textContent = messages.copy; }, 1800);
});